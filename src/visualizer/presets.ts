/**
 * Normalises any (possibly old or partial) config into a complete, valid config.
 * Used when loading projects, presets and autosaves.
 */
export function normalizeConfig(input: Partial<VisualizerConfig> | null | undefined): VisualizerConfig {
  const merged: VisualizerConfig = { ...DEFAULT_CONFIG, ...(input || {}) };
  merged.textLayers = Array.isArray(input?.textLayers)
    ? input!.textLayers.map((l) => ({ ...baseText, ...l }))
    : DEFAULT_TEXT_LAYERS.map((l) => ({ ...l }));
  merged.barCount = Math.round(Math.max(16, Math.min(256, merged.barCount)));
  merged.particleCount = Math.round(Math.max(0, Math.min(800, merged.particleCount)));
  merged.smoothing = Math.max(0, Math.min(0.97, merged.smoothing));
  return merged;
}

